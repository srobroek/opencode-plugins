// Real git clone and tag: 2.2 s at load average 49; 30 s leaves headroom for a loaded machine (AGENTS.md, Testing).
setDefaultTimeout(30_000)

const COMMIT = "b8f7a2ecb410e68d62a38464ffd800396cdb06c5"
const scratch: string[] = []
const tmp = () => {
  const dir = mkdtempSync(path.join(os.tmpdir(), "sync-cad-test-"))
  scratch.push(dir)
  return dir
}
afterEach(() => {
  for (const dir of scratch.splice(0)) rmSync(dir, { recursive: true, force: true })
})

const agent = (name: string, capabilities: string, skills = "[cad-model]") =>
  `---\nname: ${name}\ndescription: Does one CAD job.\ncapabilities: [${capabilities}]\nskills: ${skills}\n---\n\nYou are a worker.\n`
const front = (text: string) => Bun.YAML.parse(/^---\n([\s\S]*?)\n---\n/.exec(text)?.[1] ?? "") as Record<string, unknown>
const rules = (text: string) =>
  (front(text).permissions as { action: string; resource: string; effect: string }[]).map(
    ({ action, resource, effect }) => `${action} ${resource} ${effect}`,
  )

describe("parsePin", () => {
  test("round-trips through formatPin", () => {
    const pin = { repository: "https://example.test/cad-agent.git", tag: "v0.1.1", commit: COMMIT }
    expect(parsePin(formatPin(pin))).toEqual(pin)
  })

  test.each([
    ["an abbreviated commit", { repository: "r", tag: "v1", commit: "b8f7a2e" }],
    ["no tag", { repository: "r", commit: COMMIT }],
  ])("refuses %s", (_, pin) => {
    expect(() => parsePin(JSON.stringify(pin))).toThrow()
  })
})

