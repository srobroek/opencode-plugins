import { describe, expect, test } from "bun:test"
import { translateAgent } from "./claude-agents.ts"
import { parseFrontmatter } from "./convert-agent.ts"

type Rule = [action: string, resource: string, effect: "allow" | "deny" | "ask"]

function agent(rules: Rule[], extra = "", body = "\n# Prompt\n\nDo the thing.\n"): string {
  const permissions = rules
    .map(([action, resource, effect]) => `  - action: "${action}"\n    resource: "${resource}"\n    effect: ${effect}`)
    .join("\n")
  return `---\n# Generated by scripts/build.ts from agents.src/x.md. Do not edit.\ndescription: "Reviews things."\nmode: subagent\nsteps: 80\nhidden: true\nmodel: "amazon-bedrock/x"\nrequest:\n  headers:\n    x-opencode-model-role: reviewer\n${extra}permissions:\n${permissions}\n---\n${body}`
}

const frontmatter = (contents: string) => parseFrontmatter(contents).data

describe("translateAgent", () => {
  test("turns a deny-all-first rule list into a tools allowlist and keeps only Claude Code keys", () => {
    const out = translateAgent(
      "reviewer",
      agent([
        ["*", "*", "deny"],
        ["read", "*", "allow"],
        ["grep", "*", "allow"],
        ["glob", "*", "allow"],
        ["lsp_*", "*", "allow"],
        ["edit", "*", "allow"],
        ["shell", "*", "allow"],
        ["webfetch", "*", "allow"],
        ["websearch", "*", "allow"],
      ]),
    )
    expect(frontmatter(out.contents)).toEqual({
      name: "reviewer",
      description: "Reviews things.",
      tools: "Read, Grep, Glob, LSP, Edit, Write, NotebookEdit, Bash, WebFetch, WebSearch",
      maxTurns: 80,
    })
    expect(out.dropped).toEqual([])
  })

  test("turns a default-allow rule list into a disallowedTools denylist", () => {
    const out = translateAgent(
      "validator",
      agent([
        ["skill", "*", "deny"],
        ["webfetch", "*", "deny"],
        ["subagent", "*", "deny"],
      ]),
    )
    const data = frontmatter(out.contents)
    expect(data.disallowedTools).toBe("WebFetch, Agent, Skill")
    expect(data.tools).toBeUndefined()
  })

  test("never grants a resource-restricted allow", () => {
    const out = translateAgent(
      "reviewer",
      agent([
        ["*", "*", "deny"],
        ["read", "*", "allow"],
        ["shell", "git diff *", "allow"],
        ["skill", "quality-*", "allow"],
        ["edit", "specs/*", "allow"],
        ["subagent", "*", "deny"],
        ["subagent", "explore", "allow"],
      ]),
    )
    expect(frontmatter(out.contents).tools).toBe("Read")
    expect(out.dropped).toEqual(
      ["allow edit(specs/*)", "allow shell(git diff *)", "allow subagent(explore)", "allow skill(quality-*)"].map(
        (rule) => ({ rule, reason: "resource-restricted allow; dropped" }),
      ),
    )
  })

  test("a restricted deny after an allow removes the whole tool", () => {
    const out = translateAgent(
      "a",
      agent([
        ["*", "*", "deny"],
        ["read", "*", "allow"],
        ["shell", "*", "allow"],
        ["shell", "git push *", "deny"],
      ]),
    )
    expect(frontmatter(out.contents).tools).toBe("Read")
  })

  test("drops an unrestricted ask, unmapped actions and restricted asks off a tool the agent lacks, with a warning each", () => {
    const out = translateAgent(
      "a",
      agent([
        ["*", "*", "deny"],
        ["read", "*", "allow"],
        ["webfetch", "*", "ask"],
        ["shell", "git log *", "ask"],
        ["execute", "*", "allow"],
        ["question", "*", "allow"],
        ["journey*", "*", "allow"],
        ["external_directory", "*", "ask"],
      ]),
    )
    expect(frontmatter(out.contents).tools).toBe("Read")
    expect(out.dropped).toEqual([
      { rule: "ask webfetch", reason: "no per-subagent ask; denied" },
      ...["allow execute", "allow question", "allow journey*", "ask external_directory"].map((rule) => ({
        rule,
        reason: "no Claude Code tool; dropped",
      })),
    ])
    expect(out.guards).toEqual([])
  })

  test("carries a restricted ask on a kept tool as a guard, with its allow exception in order", () => {
    const out = translateAgent(
      "a",
      agent([
        ["*", "*", "deny"],
        ["read", "*", "allow"],
        ["read", "*.env", "ask"],
        ["read", "*.env.*", "ask"],
        ["read", "*.env.example", "allow"],
      ]),
    )
    expect(frontmatter(out.contents).tools).toBe("Read")
    expect(out.dropped).toEqual([])
    expect(out.guards).toEqual([
      {
        tools: ["Read"],
        rules: [
          { resource: "*.env", effect: "ask" },
          { resource: "*.env.*", effect: "ask" },
          { resource: "*.env.example", effect: "allow" },
        ],
      },
    ])
  })

  test("guards a restricted ask when the agent inherits the tool through a denylist", () => {
    const out = translateAgent("a", agent([["edit", "*", "deny"], ["read", "*.env", "ask"]]))
    expect(frontmatter(out.contents).disallowedTools).toBe("Edit, Write, NotebookEdit")
    expect(out.guards).toEqual([{ tools: ["Read"], rules: [{ resource: "*.env", effect: "ask" }] }])
  })

  test("appends a note naming the tools the agent lacks, after the prompt body", () => {
    const body = "\n# Prompt\n\nRun `git diff` and load the `review-security` skill.\n"
    const out = translateAgent(
      "a",
      agent(
        [["*", "*", "deny"], ["read", "*", "allow"], ["shell", "git diff", "allow"], ["skill", "review-*", "allow"], ["browser", "*", "allow"]],
        "",
        body,
      ),
    )
    const text = parseFrontmatter(out.contents).body
    expect(text.startsWith(body)).toBe(true)
    const note = text.slice(body.length)
    expect(note).toContain("## Claude Code translation")
    expect(note).toContain("only these built-in tools: Read.")
    expect(note).toContain("You do not have Grep, Glob, LSP, Edit, Write, NotebookEdit, Bash, WebFetch, WebSearch, Agent, Skill.")
    expect(note).toContain("`browser`")
  })

  test("names the denied tools of a denylist agent in the note", () => {
    const out = translateAgent("a", agent([["edit", "*", "deny"]]))
    const note = parseFrontmatter(out.contents).body
    expect(note).toContain("You do not have Edit, Write, NotebookEdit.")
    expect(note).toContain("Read, Grep, Glob, LSP, Bash")
  })

  test.each([
    ["a primary agent", agent([["read", "*", "allow"]]).replace("mode: subagent", "mode: primary"), "primary agent"],
    ["an allowlist with no tool left", agent([["*", "*", "deny"], ["shell", "gh pr view *", "allow"]]), "no Claude Code tool survives"],
    ["a missing description", agent([]).replace('description: "Reviews things."\n', ""), "description is required"],
  ])("refuses %s", (_, text, message) => {
    expect(() => translateAgent("a", text)).toThrow(message)
  })
})
