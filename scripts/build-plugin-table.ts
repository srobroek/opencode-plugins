// Generates the plugin table in the project-scaffold skill from each plugin's package.json.
//
// Each plugins/<name>/package.json declares, under "opencode-plugins":
//
//   "scope":    "global" (loaded in every project), "project" (added per project) or
//               "internal" (not a user plugin, such as lib)
//   "signals":  project scope only, required: short strings an agent can check in a repository
//   "requires": optional names of other plugins this one needs
//
// The block between the markers in references/plugins.md is generated, never hand-edited.
//
//   bun scripts/build-plugin-table.ts          rewrite the block
//   bun scripts/build-plugin-table.ts --check  fail when the committed file is stale

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

export const SCOPES = ["global", "project", "internal"] as const
export type Scope = (typeof SCOPES)[number]

export type Entry = {
  name: string
  description: string
  scope: Scope
  signals: string[]
  requires: string[]
}

export const START = "<!-- plugin-table:start -->"
export const END = "<!-- plugin-table:end -->"
export const TABLE_FILE = "plugins/project/skills/project-scaffold/references/plugins.md"

const CONFIG_KEY = "opencode-plugins"
const NOTICE = "<!-- Generated by scripts/build-plugin-table.ts from each plugin's package.json. Do not edit; run `bun run plugin-table`. -->"

function fail(where: string, message: string): never {
  throw new Error(`${where}: ${message}`)
}

function stringList(where: string, key: string, value: unknown): string[] {
  if (!Array.isArray(value) || value.some((item) => typeof item !== "string" || !item.trim())) {
    fail(where, `"${CONFIG_KEY}.${key}" must be an array of non-empty strings`)
  }
  return value as string[]
}

/** The table view of one package.json manifest; throws a message naming the file when it is invalid. */
export function parseEntry(name: string, manifest: Record<string, unknown>): Entry {
  const where = `plugins/${name}/package.json`
  const config = (manifest[CONFIG_KEY] ?? {}) as Record<string, unknown>
  if (typeof config !== "object" || config === null || Array.isArray(config)) fail(where, `"${CONFIG_KEY}" must be an object`)
  const scope = config.scope
  if (!SCOPES.includes(scope as Scope)) fail(where, `"${CONFIG_KEY}.scope" must be one of ${SCOPES.join(", ")}`)
  const signals = config.signals === undefined ? [] : stringList(where, "signals", config.signals)
  if (scope === "project" && signals.length === 0) fail(where, `a project plugin needs "${CONFIG_KEY}.signals"`)
  if (scope !== "project" && signals.length > 0) fail(where, `"${CONFIG_KEY}.signals" applies to project plugins only`)
  const requires = config.requires === undefined ? [] : stringList(where, "requires", config.requires)
  // The package description describes the OpenCode plugin; `opencode-plugins.description`
  // describes only the skills that Claude Code and Codex get, so it is the fallback here.
  const description = manifest.description ?? config.description
  if (typeof description !== "string" || !description.trim()) fail(where, "description must be a non-empty string")
  for (const text of [description, ...signals, ...requires]) {
    if (text.includes(START) || text.includes(END)) fail(where, "text must not contain a plugin-table marker")
  }
  return { name, description: description.trim(), scope: scope as Scope, signals, requires }
}

/** Read every plugins/<name>/package.json and check that requires names exist. */
export function readEntries(root: string): Entry[] {
  const pluginsDir = path.join(root, "plugins")
  const entries = readdirSync(pluginsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .flatMap((name) => {
      const file = path.join(pluginsDir, name, "package.json")
      if (!existsSync(file)) fail(`plugins/${name}`, "missing package.json")
      return parseEntry(name, JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>)
    })
  const names = new Set(entries.map((entry) => entry.name))
  for (const entry of entries) {
    for (const required of entry.requires) {
      if (!names.has(required)) fail(`plugins/${entry.name}/package.json`, `requires unknown plugin "${required}"`)
    }
  }
  return entries
}

/** The description up to its first sentence end. */
export function firstSentence(text: string): string {
  const flat = text.replace(/\s+/g, " ").trim()
  const match = flat.match(/^.*?[.!?](?=\s|$)/)
  return (match?.[0] ?? flat).replace(/\.$/, "")
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|")
}

function table(header: string[], rows: string[][]): string {
  const lines = [`| ${header.join(" | ")} |`, `| ${header.map(() => "---").join(" | ")} |`]
  for (const row of rows) lines.push(`| ${row.map(cell).join(" | ")} |`)
  return lines.join("\n")
}

const byName = (a: Entry, b: Entry) => a.name.localeCompare(b.name)

/** The generated block, markers included. */
export function renderBlock(entries: Entry[]): string {
  const global = entries
    .filter((entry) => entry.scope === "global")
    .sort(byName)
    .map((entry) => [entry.name, firstSentence(entry.description)])
  const project = entries
    .filter((entry) => entry.scope === "project")
    .sort(byName)
    .map((entry) => [
      entry.name,
      entry.signals.join("; "),
      entry.requires.join(", ") || "none",
    ])
  return [
    START,
    NOTICE,
    "",
    "### Global plugins",
    "",
    "Loaded in every project by the global configuration. Do not add them per project.",
    "",
    table(["Plugin", "Does"], global),
    "",
    "### Per-project plugins",
    "",
    "Add one when any of its signals holds in the repository.",
    "",
    table(["Plugin", "Add when", "Requires"], project),
    END,
  ].join("\n")
}

/** Replace the marked block in a document. The markers must be standalone lines: one start, then one end. */
export function replaceBlock(document: string, block: string): string {
  const lines = document.split("\n")
  const starts: number[] = []
  const ends: number[] = []
  lines.forEach((line, index) => {
    if (line.trim() === START) starts.push(index)
    if (line.trim() === END) ends.push(index)
  })
  const [start, end] = [starts[0], ends[0]]
  if (starts.length !== 1 || ends.length !== 1 || start === undefined || end === undefined) {
    fail(TABLE_FILE, `needs exactly one ${START} line and one ${END} line, found ${starts.length} and ${ends.length}`)
  }
  if (end < start) fail(TABLE_FILE, `${END} comes before ${START}`)
  return [...lines.slice(0, start), block, ...lines.slice(end + 1)].join("\n")
}

export type Plan = { file: string; contents: string; stale: boolean }

/** What the table file should contain and whether the committed file differs. Writes nothing. */
export function planTable(root: string): Plan {
  const file = path.join(root, TABLE_FILE)
  const current = readFileSync(file, "utf8")
  const contents = replaceBlock(current, renderBlock(readEntries(root)))
  return { file, contents, stale: contents !== current }
}

/** Check mode: the plan, with the file left untouched. */
export const checkTable = planTable

/** Write mode: apply the plan. */
export function writeTable(root: string): Plan {
  const plan = planTable(root)
  if (plan.stale) writeFileSync(plan.file, plan.contents)
  return plan
}

function main(check: boolean) {
  const root = path.resolve(import.meta.dir, "..")
  if (!check) {
    writeTable(root)
    return
  }
  const plan = checkTable(root)
  if (plan.stale) {
    console.error(`The plugin table is stale. Run \`bun run plugin-table\` and commit the result:\n  ${path.relative(root, plan.file)}`)
    process.exit(1)
  }
}

if (import.meta.main) {
  try {
    main(process.argv.includes("--check"))
  } catch (error) {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  }
}
