// Builds every plugin under plugins/ whose package.json exports point into ./dist.
//
// OpenCode installs a plugin from its own directory only (a git `::path:` spec
// packs just that subdirectory), so workspace packages such as
// @srobroek/opencode-lib are inlined. Modules the host provides at runtime stay
// external. For each export the build also writes a root shim (`index.js`,
// `tui.js`, ...) because OpenCode loads a local plugin directory by file name,
// not through package.json exports. TSX sources get the OpenTUI Solid
// transform here, because OpenCode only compiles TSX outside node_modules.
// It also composes each `agents.src/<id>.md` into the committed `agents/<id>.md`,
// inlining `{{include <fragment>}}` lines from plugins/lib/src/<fragment>.md.
//
//   bun scripts/build.ts          build all plugins
//   bun scripts/build.ts --check  fail when committed output is stale

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { createSolidTransformPlugin } from "@opentui/solid/bun-plugin"
import { composeAgentFile, generatedComment } from "../plugins/lib/src/fragments.ts"

const HOST_MODULES = [
  "@opencode/plugin",
  "@opencode/plugin/*",
  "effect",
  "effect/*",
  "@opentui/*",
  "solid-js",
  "solid-js/*",
]
const SOURCE_EXTENSIONS = [".ts", ".tsx"]

const root = path.resolve(import.meta.dir, "..")
const pluginsDir = path.join(root, "plugins")

export type Output = { file: string; contents: string }

type Entry = { shim: string; dist: string; source: string }

function entries(dir: string): Entry[] {
  const manifestPath = path.join(dir, "package.json")
  if (!existsSync(manifestPath)) return []
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as { exports?: unknown }
  const exports =
    typeof manifest.exports === "string" ? { ".": manifest.exports } : (manifest.exports as Record<string, unknown>)
  if (!exports || typeof exports !== "object") return []
  const found: Entry[] = []
  for (const [key, value] of Object.entries(exports)) {
    if (typeof value !== "string") continue
    const match = value.match(/^\.\/dist\/([\w-]+)\.js$/)
    if (!match) continue
    const name = match[1] as string
    const source = SOURCE_EXTENSIONS.map((ext) => path.join(dir, "src", `${name}${ext}`)).find(existsSync)
    if (!source) throw new Error(`${path.relative(root, dir)}: no src/${name}.ts for export "${key}"`)
    const shim = key === "." ? "index" : key.replace(/^\.\//, "")
    found.push({ shim: `${shim}.js`, dist: `dist/${name}.js`, source })
  }
  return found
}

export async function buildPlugin(dir: string): Promise<Output[]> {
  const items = entries(dir)
  if (items.length === 0) return []
  const result = await Bun.build({
    entrypoints: items.map((item) => item.source),
    root: path.join(dir, "src"),
    target: "bun",
    format: "esm",
    external: HOST_MODULES,
    splitting: false,
    minify: false,
    sourcemap: "none",
    plugins: [createSolidTransformPlugin()],
  })
  if (!result.success) throw new AggregateError(result.logs, `${path.relative(root, dir)}: build failed`)
  const header = "// Generated by scripts/build.ts. Do not edit.\n"
  const outputs: Output[] = []
  for (const artifact of result.outputs) {
    if (artifact.kind !== "entry-point") continue
    // Keep Bun's `// @bun` pragma on the first line; Bun only honours it there.
    const text = await artifact.text()
    const contents = text.startsWith("// @bun\n") ? `// @bun\n${header}${text.slice(8)}` : header + text
    outputs.push({ file: path.join(dir, "dist", artifact.path), contents })
  }
  for (const item of items) {
    outputs.push({
      file: path.join(dir, item.shim),
      contents: `${header}export { default } from "./${item.dist}"\nexport * from "./${item.dist}"\n`,
    })
  }
  return outputs
}

const AGENT_SOURCES = "agents.src"

/** The `agents/<id>.md` composed from every `agents.src/<id>.md`. */
export function composeAgents(dir: string, read?: (name: string) => string): Output[] {
  const sources = path.join(dir, AGENT_SOURCES)
  if (!existsSync(sources)) return []
  return readdirSync(sources)
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => ({
      file: path.join(dir, "agents", name),
      contents: composeAgentFile(readFileSync(path.join(sources, name), "utf8"), `${AGENT_SOURCES}/${name}`, read),
    }))
}

/** Composed agent files whose source is gone: they carry the generated comment but no build produces them. */
export function orphanAgents(dir: string, outputs: readonly Output[]): string[] {
  const agents = path.join(dir, "agents")
  if (!existsSync(agents)) return []
  const expected = new Set(outputs.map((output) => output.file))
  return readdirSync(agents)
    .filter((name) => name.endsWith(".md"))
    .map((name) => path.join(agents, name))
    .filter((file) => !expected.has(file))
    .filter((file) => readFileSync(file, "utf8").startsWith(`---\n${generatedComment(`${AGENT_SOURCES}/${path.basename(file)}`)}\n`))
}

function listFiles(dir: string): string[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.join(entry.parentPath, entry.name))
}

/** Paths whose committed contents differ from a fresh build, or that the build no longer produces. */
export function stale(dir: string, outputs: readonly Output[]): string[] {
  const expected = new Set(outputs.map((output) => output.file))
  const changed = outputs
    .filter((output) => !existsSync(output.file) || readFileSync(output.file, "utf8") !== output.contents)
    .map((output) => output.file)
  const extra = listFiles(path.join(dir, "dist")).filter((file) => !expected.has(file))
  return [...changed, ...extra]
}

async function main(check: boolean) {
  // Bun names source files relative to the working directory in its output.
  process.chdir(root)
  const dirs = readdirSync(pluginsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => path.join(pluginsDir, entry.name))
  const problems: string[] = []
  for (const dir of dirs) {
    const agents = composeAgents(dir)
    const orphans = orphanAgents(dir, agents)
    const changed = agents.filter((output) => !existsSync(output.file) || readFileSync(output.file, "utf8") !== output.contents)
    if (check) problems.push(...changed.map((output) => output.file), ...orphans)
    else {
      for (const file of orphans) rmSync(file)
      for (const output of changed) {
        mkdirSync(path.dirname(output.file), { recursive: true })
        writeFileSync(output.file, output.contents)
      }
      if (agents.length > 0) console.log(`composed ${agents.length} agent(s) in ${path.relative(root, dir)}`)
    }
    const outputs = await buildPlugin(dir)
    if (outputs.length === 0) continue
    if (check) {
      problems.push(...stale(dir, outputs))
      continue
    }
    rmSync(path.join(dir, "dist"), { recursive: true, force: true })
    for (const output of outputs) {
      mkdirSync(path.dirname(output.file), { recursive: true })
      writeFileSync(output.file, output.contents)
    }
    console.log(`built ${path.relative(root, dir)}`)
  }
  if (problems.length > 0) {
    console.error("Build output is stale. Run `bun run build` and commit the result:")
    for (const file of problems) console.error(`  ${path.relative(root, file)}`)
    process.exit(1)
  }
}

if (import.meta.main) await main(process.argv.includes("--check"))
