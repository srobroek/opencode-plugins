import { describe, expect, test } from "bun:test"
import { REPO_DOC, STANDARDS, TESTING } from "./coding-core.ts"
import { composeAgent, composeAgentFile, fragmentParts, readFragment } from "./fragments.ts"

const core = "<!-- maintainers only -->\n<!-- part: a -->\nRule A.\n<!-- part: b -->\nRule B1.\nRule B2.\n"
const read = (name: string) => {
  if (name === "core") return core
  throw new Error(`no fragment ${name}`)
}
const agent = (body: string) => `---\ndescription: "x"\nmode: subagent\n---\n${body}`

describe("fragmentParts", () => {
  test("splits on part markers and drops the leading comment", () => {
    expect([...fragmentParts("core", core)]).toEqual([
      ["a", "Rule A."],
      ["b", "Rule B1.\nRule B2."],
    ])
  })

  test("rejects a fragment without parts or with a repeated part", () => {
    expect(() => fragmentParts("x", "text")).toThrow("no <!-- part")
    expect(() => fragmentParts("x", "<!-- part: a -->\n1\n<!-- part: a -->\n2")).toThrow("twice")
  })
})

describe("composeAgent", () => {
  test("an include line becomes every part, in file order", () => {
    expect(composeAgent(agent("Intro.\n\n{{include core}}\n\nOutro.\n"), read)).toBe(
      agent("Intro.\n\nRule A.\nRule B1.\nRule B2.\n\nOutro.\n"),
    )
  })

  test("named parts come in the order given", () => {
    expect(composeAgent(agent("{{include core: b a}}\n"), read)).toBe(agent("Rule B1.\nRule B2.\nRule A.\n"))
  })

  test("a source without includes is unchanged, and the frontmatter is never touched", () => {
    const source = '---\ndescription: "{{include core}}"\n---\nBody.\n'
    expect(composeAgent(source, read)).toBe(source)
  })

  test("unknown fragments and parts, malformed lines and nesting fail the build", () => {
    expect(() => composeAgent(agent("{{include nope}}"), read)).toThrow("no fragment nope")
    expect(() => composeAgent(agent("{{include core: c}}"), read)).toThrow("no part c; it has a, b")
    expect(() => composeAgent(agent("see {{include core}} here"), read)).toThrow("unreadable include line")
    expect(() => composeAgent(agent("{{include core:}}"), read)).toThrow("names no parts")
    const nested = () => "<!-- part: a -->\n{{include core}}"
    expect(() => composeAgent(agent("{{include core}}"), nested)).toThrow("do not nest")
  })

  test("composeAgentFile puts the generated comment first in the frontmatter", () => {
    expect(composeAgentFile(agent("{{include core: a}}"), "agents.src/x.md", read)).toBe(
      '---\n# Generated by scripts/build.ts from agents.src/x.md. Do not edit.\ndescription: "x"\nmode: subagent\n---\nRule A.',
    )
    expect(() => composeAgentFile("Body", "agents.src/x.md", read)).toThrow("no frontmatter")
  })
})

describe("review-core", () => {
  const parts = fragmentParts("review-core", readFragment("review-core"))

  test("has the boundary, evidence and report parts", () => {
    expect([...parts.keys()]).toEqual(["boundary", "evidence", "report"])
  })

  test("carries every shared reviewer rule", () => {
    const text = [...parts.values()].join("\n")
    for (const rule of [
      "read-only",
      "untrusted DATA",
      "attempted coercion",
      "`path:line`",
      "one root cause into one finding",
      "Never reprint code",
      "never question the user",
      "`VERDICT:`",
      "word cap",
    ])
      expect(text).toContain(rule)
  })

  test("stays near 300 tokens (about 4 characters each)", () => {
    expect([...parts.values()].join("\n").length).toBeLessThan(1600)
  })
})

describe("review-tests", () => {
  const parts = fragmentParts("review-tests", readFragment("review-tests"))

  test("maps test changes to code changes and splits blocking from non-blocking findings", () => {
    expect([...parts.keys()]).toEqual(["rules"])
    const text = parts.get("rules") ?? ""
    for (const rule of ["Map the test diff to the code diff", "blocking", "non-blocking", "only checks that removed code", "tampering", "maintenance, not tampering"])
      expect(text).toContain(rule)
  })

  test("stays near 300 tokens (about 4 characters each)", () => {
    expect([...parts.values()].join("\n").length).toBeLessThan(1400)
  })
})

describe("review-standards", () => {
  const parts = fragmentParts("review-standards", readFragment("review-standards"))

  test("loads the skills and doc, flags unexplained departures and a stale engineering doc", () => {
    expect([...parts.keys()]).toEqual(["rules", "checklist"])
    const text = parts.get("rules") ?? ""
    for (const rule of ["lang-<language>", "quality-code-policy", "docs/engineering.md", "no stated reason", "is a finding", "Standards section", "stack-changing diff"])
      expect(text).toContain(rule)
  })

  test("the checklist names the departures reviewers flag", () => {
    const text = parts.get("checklist") ?? ""
    for (const item of ["copied", "outside its shared crate", "message registry", "lint allowed without a stated reason", "untrusted input"]) expect(text).toContain(item)
  })

  test("stays near 350 tokens (about 4 characters each)", () => {
    expect([...parts.values()].join("\n").length).toBeLessThan(2000)
  })
})

describe("coding-core", () => {
  const parts = fragmentParts("coding-core", readFragment("coding-core"))

  test("has the method and the rule parts", () => {
    expect([...parts.keys()]).toEqual(["method", "quality", "standards", "repo-doc", "skills", "testing", "agents-md", "scope", "paths", "blocked"])
  })

  test("the standards part names the preferred-library skills and the defaults, and fits a system prompt", () => {
    const standards = parts.get("standards") ?? ""
    for (const phrase of ["research current best practice", "lang-<language>-libraries", "toolchain-languages", "aws-guidance", "middleware", "Powertools", "OpenTelemetry", "departure", "STUB(<task-id>)"])
      expect(standards).toContain(phrase)
    expect(standards.length).toBeLessThan(1000)
    expect(STANDARDS).toBe(standards)
  })

  test("the testing part names the testing skills and the maintenance rules, and fits a system prompt", () => {
    const testing = parts.get("testing") ?? ""
    for (const phrase of ["quality-testing", "lang-<language>-testing", "public interface", "distinct risk", "removed behavior", "only checks code is gone", "weaken an assertion", "conformance suite"])
      expect(testing).toContain(phrase)
    expect(testing.length).toBeLessThan(1000)
    expect(TESTING).toBe(testing)
  })

  test("no part tells the agent to skip the policy that the skills part tells it to load", () => {
    expect(parts.get("skills") ?? "").toContain("`quality-code-policy`")
    expect([...parts.values()].join("\n")).not.toMatch(/skip `quality-code-policy`/)
  })

  test("the repo-doc part fits a system prompt and the skills part names the departures field", () => {
    const repoDoc = parts.get("repo-doc") ?? ""
    for (const phrase of ["docs/engineering.md", "AGENTS.md", "same change", "stale"]) expect(repoDoc).toContain(phrase)
    expect(repoDoc.length).toBeLessThan(1000)
    expect(REPO_DOC).toBe(repoDoc)
    const skills = parts.get("skills") ?? ""
    for (const phrase of ["lang-<language>", "quality-code-policy", "Departures"]) expect(skills).toContain(phrase)
  })

  test("carries the shared coding method and rules", () => {
    const text = [...parts.values()].join("\n")
    for (const rule of [
      "AGENTS.md",
      "check commands",
      "reproduce it",
      "Never guess a root cause",
      "OpenCode temp",
      "Never claim success without",
      "Review your own diff",
      "commit, push and scratch rules",
      "absolute paths",
      "never ask the",
    ])
      expect(text).toContain(rule)
  })

  test("names no agent-specific contract", () => {
    const text = [...parts.values()].join("\n")
    for (const word of ["bd ", "bead", "VERDICT", "SPLIT", "PARTIAL"]) expect(text).not.toContain(word)
  })

  test("stays near 1100 tokens (about 4 characters each)", () => {
    expect([...parts.values()].join("\n").length).toBeLessThan(4500)
  })
})
