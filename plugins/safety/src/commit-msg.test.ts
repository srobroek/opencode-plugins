import { afterAll, describe, expect, setDefaultTimeout, test } from "bun:test"
import { spawnSync } from "node:child_process"
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  realpathSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import {
  CHAINED_NAME,
  CHECKER_NAME,
  checkMessage,
  classifyHook,
  type Git,
  type InstallState,
  install,
  MARKER,
  messageBody,
  planInstall,
  uninstall,
} from "./commit-msg.ts"

// Every integration case spawns git, which spawns the hook, which spawns bun.
setDefaultTimeout(60_000)

const TRAILER = "Co-authored-by: Claude <noreply@anthropic.com>"
const HOOK_SOURCE = join(import.meta.dir, "../hooks/commit-msg")

describe("messageBody and checkMessage", () => {
  test("rejects an assistant trailer and accepts a human one", () => {
    expect(checkMessage(`fix: thing\n\n${TRAILER}\n`)).toBe(false)
    expect(checkMessage("fix: thing\n\nCo-authored-by: Ada <ada@example.com>\n")).toBe(true)
    expect(checkMessage("feat: x\n\nGenerated with [Claude Code](https://claude.ai)\n")).toBe(false)
  })

  test("ignores comment lines and the verbose diff below the scissors", () => {
    const text = `fix: thing\n\n# ${TRAILER}\n# ------------------------ >8 ------------------------\n+${TRAILER}\n`
    expect(messageBody(text)).toBe("fix: thing\n")
    expect(checkMessage(text)).toBe(true)
  })

  test("honours a configured comment character", () => {
    expect(checkMessage(`fix\n; ${TRAILER}\n`, ";")).toBe(true)
    expect(checkMessage(`fix\n# ${TRAILER}\n`, ";")).toBe(false)
  })
})

describe("classifyHook", () => {
  const bytes = (text: string) => new TextEncoder().encode(text)
  test("tells the hook kinds apart", () => {
    expect(classifyHook(undefined)).toBe("absent")
    expect(classifyHook(bytes(`#!/bin/sh\n# ${MARKER}\n`))).toBe("ours")
    expect(classifyHook(new Uint8Array([0xcf, 0xfa, 0xed, 0xfe, 1, 2]))).toBe("binary")
    expect(classifyHook(bytes("#!/bin/sh\nexec x\0y"))).toBe("binary")
    expect(classifyHook(bytes("#!/usr/bin/env bash\n# File generated by pre-commit\n"))).toBe("framework")
    expect(classifyHook(bytes("#!/bin/sh\nexec prek hook-impl\n"))).toBe("framework")
    expect(classifyHook(bytes("#!/bin/sh\necho hi\n"))).toBe("script")
  })
})

describe("planInstall", () => {
  const base: InstallState = {
    localHooks: "/r/.git/hooks",
    effectiveHooks: "/r/.git/hooks",
    existing: "absent",
    chainedExists: false,
    behindHooksPath: false,
  }

  test("writes, refreshes or chains by what is there", () => {
    expect(planInstall(base).action).toBe("write")
    expect(planInstall({ ...base, existing: "ours" }).action).toBe("refresh")
    expect(planInstall({ ...base, existing: "script" }).action).toBe("chain")
    expect(planInstall({ ...base, existing: "script", chainedExists: true }).action).toBe("refuse")
  })

  test("never touches binary or framework hooks", () => {
    expect(planInstall({ ...base, existing: "binary" }).action).toBe("refuse")
    const framework = planInstall({ ...base, existing: "framework" })
    expect(framework.action).toBe("refuse")
    if (framework.action === "refuse") expect(framework.reason).toContain("stages: [commit-msg]")
  })

  test("respects a core.hooksPath that does not delegate", () => {
    const pointed = { ...base, effectiveHooks: "/shared/hooks", hooksPath: { scope: "global", value: "/shared/hooks" } }
    const refused = planInstall(pointed)
    expect(refused.action).toBe("refuse")
    if (refused.action === "refuse") expect(refused.reason).toContain("global: /shared/hooks")
    expect(planInstall({ ...pointed, behindHooksPath: true }).action).toBe("write")
    const delegated = planInstall({ ...pointed, delegating: ["/shared/hooks"] })
    expect(delegated.action).toBe("write")
    if (delegated.action !== "refuse") expect(delegated.notes.join()).toContain("owns hook dispatch")
  })
})

const scratch = realpathSync(mkdtempSync(join(tmpdir(), "safety-commit-msg-")))
afterAll(() => rmSync(scratch, { recursive: true, force: true }))

let counter = 0

/** A temp repository whose git ignores the machine's system and global config. */
function repo(globalConfig = "") {
  const dir = join(scratch, `repo-${counter++}`)
  mkdirSync(dir)
  const gitconfig = join(dir, "..", `gitconfig-${counter}`)
  writeFileSync(gitconfig, `[user]\n\tname = Test\n\temail = test@example.com\n${globalConfig}`)
  const env: Record<string, string | undefined> = { ...process.env, GIT_CONFIG_SYSTEM: "/dev/null", GIT_CONFIG_GLOBAL: gitconfig }
  for (const key of Object.keys(env)) if (key.startsWith("GIT_") && !key.startsWith("GIT_CONFIG_")) delete env[key]
  const git: Git = (cwd, args) => {
    const result = spawnSync("git", ["-C", cwd, ...args], { encoding: "utf8", env })
    return { status: result.status, stdout: result.stdout.trim(), stderr: result.stderr.trim() }
  }
  git(dir, ["init", "-q", "-b", "main"])
  const commit = (message: string, cwd = dir) => git(cwd, ["commit", "-q", "--allow-empty", "-m", message])
  const hooks = join(dir, ".git", "hooks")
  return { dir, git, commit, hooks }
}

describe("install into a temp repository", () => {
  test("rejects an attributed commit and accepts a clean one, in every worktree", () => {
    const r = repo()
    const outcome = install({ repo: r.dir, git: r.git })
    expect(outcome.ok).toBe(true)
    expect(existsSync(join(r.hooks, CHECKER_NAME))).toBe(true)
    expect(r.commit("fix: clean").status).toBe(0)
    const refused = r.commit(`fix: attributed\n\n${TRAILER}`)
    expect(refused.status).not.toBe(0)
    expect(refused.stderr).toContain("AI-assistant attribution")

    const linked = join(scratch, `linked-${counter++}`)
    expect(r.git(r.dir, ["worktree", "add", "-q", "-b", "side", linked]).status).toBe(0)
    expect(r.commit(`fix: attributed\n\n${TRAILER}`, linked).status).not.toBe(0)
    expect(r.commit("fix: clean", linked).status).toBe(0)

    expect(install({ repo: r.dir, git: r.git }).message).toContain("Refreshed")
  })

  test("chains an existing plain hook and restores it on uninstall", () => {
    const r = repo()
    const original = `#!/bin/sh\necho ran >> "${join(r.dir, "..", `ran-${counter}`)}"\n`
    const ran = join(r.dir, "..", `ran-${counter}`)
    mkdirSync(r.hooks, { recursive: true })
    writeFileSync(join(r.hooks, "commit-msg"), original)
    chmodSync(join(r.hooks, "commit-msg"), 0o755)

    expect(install({ repo: r.dir, git: r.git }).ok).toBe(true)
    expect(readFileSync(join(r.hooks, CHAINED_NAME), "utf8")).toBe(original)
    expect(r.commit("fix: clean").status).toBe(0)
    expect(readFileSync(ran, "utf8")).toBe("ran\n")
    expect(r.commit(`fix: x\n\n${TRAILER}`).status).not.toBe(0)
    expect(readFileSync(ran, "utf8")).toBe("ran\n")

    expect(uninstall({ repo: r.dir, git: r.git }).ok).toBe(true)
    expect(readFileSync(join(r.hooks, "commit-msg"), "utf8")).toBe(original)
    expect(existsSync(join(r.hooks, CHAINED_NAME))).toBe(false)
    expect(existsSync(join(r.hooks, CHECKER_NAME))).toBe(false)
  })

  test("leaves a framework-managed hook untouched", () => {
    const r = repo()
    const framework = "#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\nexit 0\n"
    mkdirSync(r.hooks, { recursive: true })
    writeFileSync(join(r.hooks, "commit-msg"), framework)
    const outcome = install({ repo: r.dir, git: r.git })
    expect(outcome.ok).toBe(false)
    expect(readFileSync(join(r.hooks, "commit-msg"), "utf8")).toBe(framework)
    expect(existsSync(join(r.hooks, CHECKER_NAME))).toBe(false)
  })

  test("refuses when core.hooksPath sends git elsewhere, unless told it delegates", () => {
    const r = repo()
    r.git(r.dir, ["config", "core.hooksPath", ".githooks"])
    const refused = install({ repo: r.dir, git: r.git })
    expect(refused.ok).toBe(false)
    expect(refused.message).toContain("local: .githooks")
    expect(existsSync(join(r.hooks, "commit-msg"))).toBe(false)
    const forced = install({ repo: r.dir, git: r.git, behindHooksPath: true })
    expect(forced.ok).toBe(true)
    expect(forced.message).toContain("owns hook dispatch")
  })

  test("the shipped hook works from a global core.hooksPath and still runs the repository's own hook", () => {
    const shared = join(scratch, `shared-${counter++}`)
    mkdirSync(shared)
    symlinkSync(HOOK_SOURCE, join(shared, "commit-msg"))
    const r = repo(`[core]\n\thooksPath = ${shared}\n`)
    const ran = join(scratch, `ran-local-${counter}`)
    mkdirSync(r.hooks, { recursive: true })
    writeFileSync(join(r.hooks, "commit-msg"), `#!/bin/sh\necho local >> "${ran}"\n`)
    chmodSync(join(r.hooks, "commit-msg"), 0o755)

    expect(r.commit(`fix: x\n\n${TRAILER}`).status).not.toBe(0)
    expect(existsSync(ran)).toBe(false)
    expect(r.commit("fix: clean").status).toBe(0)
    expect(readFileSync(ran, "utf8")).toBe("local\n")
  })
})
